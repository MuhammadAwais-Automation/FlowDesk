/**
 * Writes the REAL generated bridge scripts out as probe files, so they run in
 * the live LinkedIn page exactly as the app would send them.
 *
 * Unit tests assert properties of these strings; this proves the strings work
 * against the real API. Re-implementing the logic inside a hand-written probe
 * would test a copy — precisely the mistake worth avoiding, since a copy can
 * pass while the thing that ships is broken.
 *
 * Dev-only. The emitted probes are read-only by construction: no send script is
 * ever written here, because a probe runs the moment it is saved and a send
 * must never happen without the user approving that exact message first.
 *
 *   node scripts/emit-linkedin-probes.mjs [conversationUrn]
 */
import { build } from 'esbuild'
import { writeFile, mkdir } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outFile = join(root, 'node_modules', '.cache', 'linkedinBridge.mjs')

await mkdir(dirname(outFile), { recursive: true })
await build({
  entryPoints: [join(root, 'electron', 'linkedinBridge.ts')],
  outfile: outFile,
  format: 'esm',
  platform: 'neutral',
  bundle: false,
})

const readOutFile = join(root, 'node_modules', '.cache', 'linkedinReadBridge.mjs')
await build({
  entryPoints: [join(root, 'electron', 'linkedinReadBridge.ts')],
  outfile: readOutFile,
  format: 'esm',
  platform: 'neutral',
  bundle: true,
})

const bridge = await import(pathToFileURL(outFile).href)
const readBridge = await import(pathToFileURL(readOutFile).href)
const conversationUrn = process.argv[2] || null

const probes = {
  'li-b1-status': bridge.statusScript(),
  'li-b2-list-chats': bridge.listChatsScript({ limit: 10 }),
  'li-b3-unread': bridge.unreadScript(),
  'li-b4-find-people': bridge.findPeopleScript(''),
  'li-b6-feed': readBridge.feedScript({ limit: 15 }),
  'li-b7-search': readBridge.searchScript({ query: 'ai developer', limit: 5 }),
  'li-b8-my-posts': readBridge.myPostsScript({ limit: 5 }),
  'li-b9-notifications': readBridge.notificationsScript({ limit: 8 }),
  'li-b10-comments': readBridge.postCommentsScript({ activityId: process.argv[3] || '0', limit: 5 }),
}

if (conversationUrn) {
  probes['li-b5-list-messages'] = bridge.listMessagesScript({ conversationUrn, limit: 15 })
}

for (const [name, script] of Object.entries(probes)) {
  const body = [
    '// @target linkedin.com',
    '// GENERATED by scripts/emit-linkedin-probes.mjs — do not edit by hand.',
    '// This is the exact script electron/linkedin.ts sends to the page.',
    `return await ${script}`,
    '',
  ].join('\n')
  await writeFile(join(root, 'probes', `${name}.js`), body, 'utf8')
  console.log(`wrote probes/${name}.js (${script.length} chars)`)
}
