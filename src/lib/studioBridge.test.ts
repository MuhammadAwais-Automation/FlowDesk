// @vitest-environment jsdom
import { describe, it, expect } from 'vitest'
import { JSDOM } from 'jsdom'
import { isBridgeMessage, BRIDGE_SCRIPT, EFFECT_ATTR } from './studioBridge'
import { PANEL_PROPERTIES } from './studioNode'

describe('isBridgeMessage', () => {
  it('accepts a styles message', () => {
    expect(isBridgeMessage({ source: 'fd-bridge', type: 'styles', elementId: 'e1', styles: { width: '10px' } })).toBe(true)
  })

  it('accepts a tree message', () => {
    expect(isBridgeMessage({ source: 'fd-bridge', type: 'tree', nodes: [] })).toBe(true)
  })

  it('rejects a message from another frame with no source marker', () => {
    expect(isBridgeMessage({ type: 'styles', elementId: 'e1' })).toBe(false)
  })

  it('rejects an unknown type', () => {
    expect(isBridgeMessage({ source: 'fd-bridge', type: 'evaluate' })).toBe(false)
  })

  it('accepts an artboards message', () => {
    expect(isBridgeMessage({ source: 'fd-bridge', type: 'artboards', boards: [{ id: 'a1', name: 'Cover' }] })).toBe(true)
  })

  it('accepts an effect message (Ruling D2)', () => {
    expect(isBridgeMessage({ source: 'fd-bridge', type: 'effect', elementId: 'e1', params: { kind: 'neon' } })).toBe(true)
    expect(isBridgeMessage({ source: 'fd-bridge', type: 'effect', elementId: 'e1', params: null })).toBe(true)
  })
})

describe('BRIDGE_SCRIPT', () => {
  it('handles both host commands', () => {
    expect(BRIDGE_SCRIPT).toContain('readStyles')
    expect(BRIDGE_SCRIPT).toContain('applyStyles')
  })

  it('reads styles through the shared property list rather than dumping everything', () => {
    expect(BRIDGE_SCRIPT).toContain('FD_PANEL_PROPERTIES')
  })

  it('handles the readArtboards command', () => {
    expect(BRIDGE_SCRIPT).toContain('readArtboards')
  })

  it('handles every LayerCommand variant except setLocked, which stays editor-only', () => {
    expect(BRIDGE_SCRIPT).toContain("d.cmd === 'reorder'")
    expect(BRIDGE_SCRIPT).toContain("d.cmd === 'group'")
    expect(BRIDGE_SCRIPT).toContain("d.cmd === 'ungroup'")
    expect(BRIDGE_SCRIPT).toContain("d.cmd === 'setHidden'")
    expect(BRIDGE_SCRIPT).toContain("d.cmd === 'rename'")
    expect(BRIDGE_SCRIPT).toContain("d.cmd === 'delete'")
    expect(BRIDGE_SCRIPT).toContain("d.cmd === 'duplicate'")
    expect(BRIDGE_SCRIPT).not.toContain("d.cmd === 'setLocked'")
  })

  it('handles the effect read/write commands (Ruling D2)', () => {
    expect(BRIDGE_SCRIPT).toContain('readEffect')
    expect(BRIDGE_SCRIPT).toContain('writeEffect')
    expect(BRIDGE_SCRIPT).toContain(EFFECT_ATTR)
  })

  it('keeps FD_PANEL_PROPERTIES in exact sync with PANEL_PROPERTIES', () => {
    // FD_PANEL_PROPERTIES is generated by JSON.stringify(PANEL_PROPERTIES) at
    // module-eval time (see studioBridge.ts), so extending PANEL_PROPERTIES
    // extends the injected script automatically. This test protects that
    // contract against ever being broken by a future edit that hardcodes the
    // list in the template string instead of interpolating it.
    const match = BRIDGE_SCRIPT.match(/var FD_PANEL_PROPERTIES = (\[.*?\]);/)
    expect(match).not.toBeNull()
    const embedded = JSON.parse(match![1])
    expect(embedded).toEqual([...PANEL_PROPERTIES])
  })
})

/**
 * Executes BRIDGE_SCRIPT against a real (jsdom) DOM — not mocked postMessage
 * assertions — so these tests are evidence the mutations, id assignment and
 * `sealed` persistence path actually work, not just that the right strings
 * appear in the source. `runScripts: 'outside-only'` lets `window.eval` run
 * the injected script inside the window's own realm, exactly like the real
 * iframe does; `parent` defaults to the window itself here (no real frame),
 * so the script's `parent.postMessage` calls loop back to this same window,
 * where the harness below listens for them.
 */
function createBridge(bodyHtml: string) {
  const dom = new JSDOM(`<!doctype html><html><body>${bodyHtml}</body></html>`, {
    runScripts: 'outside-only',
    url: 'https://example.org/',
  })
  const win = dom.window as unknown as Window & typeof globalThis
  win.eval(BRIDGE_SCRIPT)

  async function post(msg: unknown): Promise<unknown[]> {
    const received: unknown[] = []
    const onMessage = (e: MessageEvent) => { received.push(e.data) }
    win.addEventListener('message', onMessage as EventListener)
    win.postMessage(msg, '*')
    // Give jsdom's task queue enough turns to dispatch both the posted
    // command and whatever the script posts back in response.
    await new Promise(resolve => setTimeout(resolve, 20))
    win.removeEventListener('message', onMessage as EventListener)
    return received
  }

  return { win, document: win.document, post }
}

describe('BRIDGE_SCRIPT executed against a real DOM', () => {
  it('assigns ids on load and seals the artboard', async () => {
    const bridge = createBridge('<div class="fd-artboard" data-fd-id="a1"><h1>Title</h1></div>')
    // seal() runs synchronously during window.eval(); give the queued
    // postMessage a turn to land.
    await new Promise(resolve => setTimeout(resolve, 20))
    const h1 = bridge.document.querySelector('h1')
    expect(h1?.hasAttribute('data-fd-el')).toBe(true)
  })

  it('reorder moves an element in front of another sibling and persists via sealed', async () => {
    const bridge = createBridge(
      '<div class="fd-artboard" data-fd-id="a1">' +
        '<div data-fd-el="e1">A</div><div data-fd-el="e2">B</div><div data-fd-el="e3">C</div>' +
      '</div>',
    )
    const msgs = await bridge.post({ cmd: 'reorder', elementId: 'e3', beforeId: 'e1' })
    const board = bridge.document.querySelector('.fd-artboard')!
    const order = Array.from(board.children).map(c => c.getAttribute('data-fd-el'))
    expect(order).toEqual(['e3', 'e1', 'e2'])
    const sealed = msgs.find((m: any) => m.__fdCanvas === 'sealed') as any
    expect(sealed).toBeTruthy()
    expect(sealed.artboardId).toBe('a1')
  })

  it('reorder with beforeId null moves the element to the front (end of DOM order)', async () => {
    const bridge = createBridge(
      '<div class="fd-artboard" data-fd-id="a1">' +
        '<div data-fd-el="e1">A</div><div data-fd-el="e2">B</div>' +
      '</div>',
    )
    await bridge.post({ cmd: 'reorder', elementId: 'e1', beforeId: null })
    const board = bridge.document.querySelector('.fd-artboard')!
    const order = Array.from(board.children).map(c => c.getAttribute('data-fd-el'))
    expect(order).toEqual(['e2', 'e1'])
  })

  it('group wraps the selected elements, preserving order and ids, and the wrapper gets its own id', async () => {
    const bridge = createBridge(
      '<div class="fd-artboard" data-fd-id="a1">' +
        '<div data-fd-el="e1">A</div><div data-fd-el="e2">B</div><div data-fd-el="e3">C</div>' +
      '</div>',
    )
    await bridge.post({ cmd: 'group', elementIds: ['e2', 'e1'] })
    const board = bridge.document.querySelector('.fd-artboard')!
    // e3 stays a direct sibling of the new wrapper; e1/e2 move inside it in
    // original document order regardless of selection order.
    expect(board.children.length).toBe(2)
    const wrapper = board.querySelector(':scope > div:not([data-fd-el="e3"])') as HTMLElement
    expect(wrapper.hasAttribute('data-fd-el')).toBe(true)
    expect(wrapper.getAttribute('data-fd-el')).not.toBe('e1')
    expect(wrapper.getAttribute('data-fd-el')).not.toBe('e2')
    const kids = Array.from(wrapper.children).map(c => c.getAttribute('data-fd-el'))
    expect(kids).toEqual(['e1', 'e2'])
  })

  it('ungroup unwraps a group back to the parent, preserving child ids', async () => {
    const bridge = createBridge(
      '<div class="fd-artboard" data-fd-id="a1">' +
        '<div data-fd-el="wrap"><div data-fd-el="e1">A</div><div data-fd-el="e2">B</div></div>' +
      '</div>',
    )
    await bridge.post({ cmd: 'ungroup', elementId: 'wrap' })
    const board = bridge.document.querySelector('.fd-artboard')!
    expect(board.querySelector('[data-fd-el="wrap"]')).toBeNull()
    const order = Array.from(board.children).map(c => c.getAttribute('data-fd-el'))
    expect(order).toEqual(['e1', 'e2'])
  })

  it('setHidden sets display:none and can be reversed', async () => {
    const bridge = createBridge('<div class="fd-artboard" data-fd-id="a1"><div data-fd-el="e1">A</div></div>')
    await bridge.post({ cmd: 'setHidden', elementId: 'e1', hidden: true })
    const el = bridge.document.querySelector('[data-fd-el="e1"]') as HTMLElement
    expect(el.style.display).toBe('none')
    await bridge.post({ cmd: 'setHidden', elementId: 'e1', hidden: false })
    expect(el.style.display).toBe('')
  })

  it('rename writes a custom name that fdLabel prefers over text content', async () => {
    const bridge = createBridge('<div class="fd-artboard" data-fd-id="a1"><div data-fd-el="e1">Original text</div></div>')
    await bridge.post({ cmd: 'rename', elementId: 'e1', name: 'Headline' })
    const el = bridge.document.querySelector('[data-fd-el="e1"]') as HTMLElement
    expect(el.getAttribute('data-fd-name')).toBe('Headline')
  })

  it('delete removes the element and refuses to delete an artboard itself', async () => {
    const bridge = createBridge('<div class="fd-artboard" data-fd-id="a1"><div data-fd-el="e1">A</div></div>')
    const msgs = await bridge.post({ cmd: 'delete', elementId: 'e1' })
    expect(bridge.document.querySelector('[data-fd-el="e1"]')).toBeNull()
    expect(msgs.some((m: any) => m.__fdCanvas === 'cleared')).toBe(true)

    const board = bridge.document.querySelector('.fd-artboard')!
    const boardId = board.getAttribute('data-fd-el')
    if (boardId) {
      const before = bridge.document.body.innerHTML
      await bridge.post({ cmd: 'delete', elementId: boardId })
      expect(bridge.document.body.innerHTML).toBe(before)
    }
  })

  it('duplicate clones the element with fresh ids for the clone and every descendant', async () => {
    const bridge = createBridge(
      '<div class="fd-artboard" data-fd-id="a1">' +
        '<div data-fd-el="e1"><span data-fd-el="e1a">child</span></div>' +
      '</div>',
    )
    await bridge.post({ cmd: 'duplicate', elementId: 'e1' })
    const board = bridge.document.querySelector('.fd-artboard')!
    const tops = Array.from(board.children).map(c => c.getAttribute('data-fd-el'))
    expect(tops.length).toBe(2)
    expect(tops[0]).toBe('e1')
    const cloneId = tops[1]
    expect(cloneId).not.toBe('e1')
    expect(cloneId).not.toBeNull()
    const cloneChildId = board.querySelector(`[data-fd-el="${cloneId}"] [data-fd-el]`)?.getAttribute('data-fd-el')
    expect(cloneChildId).not.toBe('e1a')
    expect(cloneChildId).not.toBeNull()
  })

  it('setLocked is never handled by the bridge — it never mutates the DOM or seals', async () => {
    const bridge = createBridge('<div class="fd-artboard" data-fd-id="a1"><div data-fd-el="e1">A</div></div>')
    const before = bridge.document.body.innerHTML
    const msgs = await bridge.post({ cmd: 'setLocked', elementId: 'e1', locked: true })
    expect(bridge.document.body.innerHTML).toBe(before)
    expect(msgs.some((m: any) => m.__fdCanvas === 'sealed')).toBe(false)
  })

  describe('Ruling D2: effect params round-trip through data-fd-effect', () => {
    it('writeEffect stores the exact params and echoes them back', async () => {
      const bridge = createBridge('<div class="fd-artboard" data-fd-id="a1"><h1 data-fd-el="e1">Hi</h1></div>')
      const params = { kind: 'neon', intensity: 60, color: '#0ff' }
      const msgs = await bridge.post({ cmd: 'writeEffect', elementId: 'e1', params })
      const el = bridge.document.querySelector('[data-fd-el="e1"]') as HTMLElement
      expect(el.getAttribute(EFFECT_ATTR)).toBe(JSON.stringify(params))
      const effectMsg = msgs.find((m: any) => m.type === 'effect') as any
      expect(effectMsg?.params).toEqual(params)
      expect(msgs.some((m: any) => m.__fdCanvas === 'sealed')).toBe(true)
    })

    it('readEffect recovers the same params after a simulated reload (fresh bridge, same HTML)', async () => {
      const params = { kind: 'shadow', offset: 10, direction: 45, blur: 4, color: '#000000' }
      // Simulate "save, reload": write once, capture the persisted HTML, then
      // start a brand new bridge instance from that HTML — nothing carries
      // over except what is literally in the markup.
      const writer = createBridge('<div class="fd-artboard" data-fd-id="a1"><h1 data-fd-el="e1">Hi</h1></div>')
      await writer.post({ cmd: 'writeEffect', elementId: 'e1', params })
      const persistedHtml = writer.document.querySelector('.fd-artboard')!.outerHTML

      const reloaded = createBridge(persistedHtml)
      const msgs = await reloaded.post({ cmd: 'readEffect', elementId: 'e1' })
      const effectMsg = msgs.find((m: any) => m.type === 'effect') as any
      expect(effectMsg?.params).toEqual(params)
    })

    it('writeEffect with null params clears the attribute (effect removed)', async () => {
      const bridge = createBridge('<div class="fd-artboard" data-fd-id="a1"><h1 data-fd-el="e1">Hi</h1></div>')
      await bridge.post({ cmd: 'writeEffect', elementId: 'e1', params: { kind: 'hollow', thickness: 2, color: '#fff' } })
      const msgs = await bridge.post({ cmd: 'writeEffect', elementId: 'e1', params: null })
      const el = bridge.document.querySelector('[data-fd-el="e1"]') as HTMLElement
      expect(el.hasAttribute(EFFECT_ATTR)).toBe(false)
      const effectMsg = msgs.find((m: any) => m.type === 'effect') as any
      expect(effectMsg?.params).toBeNull()
    })

    it('readEffect returns null, not a crash, for a node that never had an effect', async () => {
      const bridge = createBridge('<div class="fd-artboard" data-fd-id="a1"><h1 data-fd-el="e1">Hi</h1></div>')
      const msgs = await bridge.post({ cmd: 'readEffect', elementId: 'e1' })
      const effectMsg = msgs.find((m: any) => m.type === 'effect') as any
      expect(effectMsg?.params).toBeNull()
    })
  })
})
